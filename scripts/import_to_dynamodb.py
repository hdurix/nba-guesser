#!/usr/bin/env python3
"""Import historical quiz data from results.json into DynamoDB.

Reads results.json (generated by fetch_poll_history.py) and writes:
  - Quiz metadata → nba-guesser-quizzes table
  - Individual votes → nba-guesser-answers table

Uses BatchWriteItem (max 25 items per batch) for performance.

Prerequisites:
  pip install boto3
  AWS credentials configured (profile "perso", region eu-west-3)

Usage:
  python3 scripts/import_to_dynamodb.py                  # dry-run (default)
  python3 scripts/import_to_dynamodb.py --execute        # actually write to DynamoDB
"""

import json
import os
import sys
import time

import boto3
from botocore.config import Config

RESULTS_FILE = os.path.join(os.path.dirname(__file__), "..", "results.json")
QUIZZES_TABLE = "nba-guesser-quizzes"
ANSWERS_TABLE = "nba-guesser-answers"
REGION = "eu-west-3"
PROFILE = "perso"
CHAT_ID = "-1001648179935"
BATCH_SIZE = 25


def load_results():
    with open(RESULTS_FILE) as f:
        return json.load(f)


def build_quiz_item(quiz):
    """Build a DynamoDB item for the quizzes table."""
    poll_id = f"legacy-{quiz['message_id']}"
    item = {
        "poll_id": {"S": poll_id},
        "chat_id": {"S": CHAT_ID},
        "date": {"S": quiz["date"]},
        "message_id": {"N": str(quiz["message_id"])},
        "correct_answer": {"S": quiz["correct_answer"]},
        "total_voters": {"N": str(quiz["total_voters"])},
    }
    if quiz.get("correct_option_index") is not None:
        item["correct_option_index"] = {"N": str(quiz["correct_option_index"])}
    if quiz.get("options"):
        item["options"] = {"L": [{"S": o} for o in quiz["options"]]}
    return item


def build_answer_items(quiz):
    """Build DynamoDB items for the answers table."""
    poll_id = f"legacy-{quiz['message_id']}"
    items = []
    for vote in quiz.get("votes", []):
        if vote.get("user_id") is None:
            continue
        item = {
            "poll_id": {"S": poll_id},
            "user_id": {"N": str(vote["user_id"])},
            "date": {"S": quiz["date"]},
            "timestamp": {"S": quiz["date"]},
        }
        if vote.get("user_name"):
            item["user_name"] = {"S": vote["user_name"]}
        if vote.get("option_index") is not None:
            item["option_index"] = {"N": str(vote["option_index"])}
            is_correct = vote["option_index"] == quiz.get("correct_option_index")
            item["correct"] = {"BOOL": is_correct}
        items.append(item)
    return items


def batch_write(client, table, items, dry_run):
    """Write items in batches of 25. Returns number of items written."""
    written = 0
    for i in range(0, len(items), BATCH_SIZE):
        batch = items[i : i + BATCH_SIZE]
        requests = [{"PutRequest": {"Item": item}} for item in batch]

        if dry_run:
            written += len(batch)
            continue

        response = client.batch_write_item(RequestItems={table: requests})
        written += len(batch)

        # Handle unprocessed items with exponential backoff
        unprocessed = response.get("UnprocessedItems", {}).get(table, [])
        retries = 0
        while unprocessed and retries < 5:
            retries += 1
            time.sleep(2**retries * 0.1)
            response = client.batch_write_item(RequestItems={table: unprocessed})
            unprocessed = response.get("UnprocessedItems", {}).get(table, [])

        if unprocessed:
            print(f"  WARNING: {len(unprocessed)} items failed after retries", file=sys.stderr)
            written -= len(unprocessed)

    return written


def main():
    dry_run = "--execute" not in sys.argv

    if dry_run:
        print("DRY RUN — pass --execute to actually write to DynamoDB\n")

    if not os.path.exists(RESULTS_FILE):
        print(f"Error: {RESULTS_FILE} not found. Run fetch_poll_history.py first.", file=sys.stderr)
        sys.exit(1)

    data = load_results()
    quizzes = data.get("quizzes", [])
    print(f"Loaded {len(quizzes)} quizzes from results.json")

    # Build all items
    quiz_items = []
    answer_items = []
    for quiz in quizzes:
        quiz_items.append(build_quiz_item(quiz))
        answer_items.extend(build_answer_items(quiz))

    print(f"  → {len(quiz_items)} quiz items for {QUIZZES_TABLE}")
    print(f"  → {len(answer_items)} answer items for {ANSWERS_TABLE}")

    if not dry_run:
        session = boto3.Session(profile_name=PROFILE, region_name=REGION)
        client = session.client("dynamodb", config=Config(retries={"max_attempts": 3, "mode": "adaptive"}))
    else:
        client = None

    # Write quizzes
    print(f"\nWriting to {QUIZZES_TABLE}...")
    q_written = batch_write(client, QUIZZES_TABLE, quiz_items, dry_run)
    print(f"  ✓ {q_written}/{len(quiz_items)} quiz items written")

    # Write answers
    print(f"\nWriting to {ANSWERS_TABLE}...")
    a_written = batch_write(client, ANSWERS_TABLE, answer_items, dry_run)
    print(f"  ✓ {a_written}/{len(answer_items)} answer items written")

    # Summary
    print(f"\n{'DRY RUN ' if dry_run else ''}Summary:")
    print(f"  Quizzes: {q_written}")
    print(f"  Answers: {a_written}")

    if not dry_run:
        # Validation: scan counts
        print("\nValidating item counts...")
        q_count = client.scan(TableName=QUIZZES_TABLE, Select="COUNT")["Count"]
        a_count = client.scan(TableName=ANSWERS_TABLE, Select="COUNT")["Count"]
        print(f"  {QUIZZES_TABLE}: {q_count} items")
        print(f"  {ANSWERS_TABLE}: {a_count} items")

        if q_count >= q_written and a_count >= a_written:
            print("\n  ✓ Validation passed!")
        else:
            print("\n  ⚠ Counts don't match — some items may have failed", file=sys.stderr)


if __name__ == "__main__":
    main()
